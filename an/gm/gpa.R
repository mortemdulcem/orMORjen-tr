suppressMessages({Sys.setenv(RGL_USE_NULL="TRUE"); library(geomorph)})
d <- read.csv('/home/claude/an/gm/elle_lm.csv')
A <- arrayspecs(as.matrix(d[, -(1:2)]), 14, 3)
dimnames(A)[[3]] <- d$olgu
g <- gpagen(A, print.progress = FALSE)
cat("n =", nrow(d), " E =", sum(d$cinsiyet=="E"), " K =", sum(d$cinsiyet=="K"), "\n")
gdf <- geomorph.data.frame(shape = g$coords, cs = g$Csize, sex = factor(d$cinsiyet))
cat("\n--- Centroid boyutu (mm) ---\n"); print(tapply(g$Csize, d$cinsiyet, function(x) round(c(ort=mean(x), ss=sd(x)), 1)))
cat("\n--- Procrustes ANOVA: bicim ~ cinsiyet (10000 permutasyon) ---\n")
f1 <- procD.lm(shape ~ sex, data = gdf, iter = 9999, print.progress = FALSE); print(summary(f1)$table)
cat("\n--- bicim ~ log(boyut) + cinsiyet (allometri ayiklanmis) ---\n")
f2 <- procD.lm(shape ~ log(cs) + sex, data = gdf, iter = 9999, print.progress = FALSE); print(summary(f2)$table)
p <- gm.prcomp(g$coords); cat("\n--- PCA: ilk 4 bilesenin aciklanan varyans orani ---\n"); print(round(summary(p)$PC.summary[2, 1:4], 3))
write.csv(data.frame(olgu=d$olgu, cinsiyet=d$cinsiyet, Csize=round(g$Csize,3), round(p$x[,1:4],5)), '/home/claude/an/gm/gpa_skor.csv', row.names=FALSE)
