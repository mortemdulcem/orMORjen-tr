# -*- coding: utf-8 -*-
"""Arastirmaci-duzeltmeli olgu icin 3D Slicer paketi: arastirmacinin kendi klasoru
(BT + landmark + egri + sahne, DEGISTIRILMEDEN) + elle_olc.py ile ayni cagriyla uretilen
segmentasyon + denetim gorseli + OKU.txt (degerler elle_olc raporundan, elle yazilmaz).
Kullanim: python3 paket_elle.py <denek> <dicom_klasoru> <slicer_klasoru>
"""
import sys, os, json, shutil, glob
sys.path.insert(0, '/home/claude/orbita_hat'); sys.path.insert(0, '/home/claude/an')
import numpy as np, nrrd, onisle, params, rayseg

denek, dcm, kl = sys.argv[1:4]
OUT = '/home/claude/%s_elle_teslim' % denek
RAP = json.load(open('/home/claude/an/out/elle/%s_ELLE_OLCUM.json' % denek, encoding='utf-8'))
o = RAP['olcum']
shutil.rmtree(OUT, ignore_errors=True); shutil.copytree(kl, OUT)

hacim, bilgi = (onisle.nrrd_hacim(dcm) if dcm.endswith('.nrrd') else onisle.dicom_hacim(dcm))
ct = np.transpose(hacim, (2, 1, 0))
org = np.array(bilgi['origin'], float)
rows = np.diag([bilgi['PixelSpacing'][0], bilgi['PixelSpacing'][1], bilgi['kesit_araligi']])
vox = abs(float(np.linalg.det(rows)))
lm, egri = params.load_scene(kl)
for s in ('r', 'l'):                      # ad uyarlamasi elle_olc.py ile AYNI olmali (ayni olcum)
    if 'apeks-' + s in lm:
        lm['apex-' + s] = lm.pop('apeks-' + s)
    if 'mfo-' + s in lm and 'fmo-' + s not in lm:
        lm['fmo-' + s] = lm.pop('mfo-' + s)
    if 'fso-' + s in lm and 'mso-' + s not in lm:
        lm['mso-' + s] = lm.pop('fso-' + s)
if 'sag' not in egri:
    for k in ('sağ', 'sa'):
        if k in egri:
            egri['sag'] = egri[k]; break
for S in ('sag', 'sol'):                  # 'rim_sag', 'sol' gibi adlar
    if S not in egri:
        ad = sorted(k for k in egri if k.endswith(S) or ('_%s_' % S) in k)
        if ad:
            egri[S] = egri[ad[0]]
M = {s: rayseg.kohort_maskesi(ct, rows, org, lm, s, rim_curve=np.asarray(egri[S], float))['maske']
     for s, S in (('r', 'sag'), ('l', 'sol'))}
h = {s: M[s].sum() * vox / 1000. for s in M}
dv = (abs(h['r'] - o['hacim_sag']), abs(h['l'] - o['hacim_sol']))
assert max(dv) < 0.01, 'maske raporla tutmuyor %s' % (dv,)

# BT geometrisi arastirmacinin NRRD'siyle ayni olmali (segmentasyon onun ustune oturur)
bn = [f for f in glob.glob(kl + '/*.nrrd') if 'seg' not in f.lower()]
hb = nrrd.read_header(max(bn, key=os.path.getsize))
assert list(hb['sizes']) == list(ct.shape), (hb['sizes'], ct.shape)
assert np.allclose(hb['space origin'], org, atol=1e-3), (hb['space origin'], org)

lab = np.zeros(ct.shape, np.uint8); lab[M['r']] = 1; lab[M['l']] = 2
ext = '0 %d 0 %d 0 %d' % (ct.shape[0] - 1, ct.shape[1] - 1, ct.shape[2] - 1)
hdr = {'type': 'unsigned char', 'dimension': 3, 'space': 'left-posterior-superior',
       'sizes': list(ct.shape), 'space directions': rows, 'kinds': ['domain'] * 3,
       'encoding': 'gzip', 'space origin': org,
       'Segmentation_ContainedRepresentationNames': 'Binary labelmap|',
       'Segmentation_ConversionParameters': '',
       'Segmentation_MasterRepresentation': 'Binary labelmap',
       'Segmentation_ReferenceImageExtentOffset': '0 0 0'}
for i, (nm, col) in enumerate((('sag', '0.2 0.9 0.2'), ('sol', '0.9 0.2 0.2'))):
    hdr.update({'Segment%d_ID' % i: nm, 'Segment%d_Name' % i: nm,
                'Segment%d_NameAutoGenerated' % i: '0', 'Segment%d_Color' % i: col,
                'Segment%d_LabelValue' % i: str(i + 1), 'Segment%d_Layer' % i: '0',
                'Segment%d_Extent' % i: ext,
                'Segment%d_Tags' % i: 'Segmentation.Status:inprogress|'})
nrrd.write(OUT + '/%s_Segmentation.seg.nrrd' % denek, lab, hdr, compression_level=4)

import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
zs = np.where(lab.any(axis=(0, 1)))[0]
fig, ax = plt.subplots(3, 4, figsize=(14, 11.4))
for a, z in zip(ax.ravel(), np.linspace(zs.min(), zs.max(), 12).astype(int)):
    a.imshow(ct[:, :, z].T, cmap='gray', vmin=-200, vmax=1800)
    a.contour(lab[:, :, z].T == 1, levels=[0.5], colors='lime', linewidths=1.0)
    a.contour(lab[:, :, z].T == 2, levels=[0.5], colors='red', linewidths=1.0)
    a.set_title('z=%d' % z, fontsize=8); a.axis('off')
fig.suptitle('%s — arastirmaci landmarklariyla kavite maskesi (yesil sag, kirmizi sol)' % denek)
fig.tight_layout(); fig.savefig(OUT + '/%s_denetim.png' % denek, dpi=150)

K = ['OW', 'OH', 'OI', 'APalan', 'APcevre', 'derinlik', 'hacim', 'hacimK',
     'kal_sup', 'kal_inf', 'kal_med', 'kal_lat']
L = ['%s — arastirmaci landmarklariyla olcum' % denek, '',
     'Kaynak: arastirmacinin Slicer landmarklari + rim egrileri (degistirilmeden).',
     'Maske ve olcum: donmus hattin 6-8. adimlari (rayseg.kohort_maskesi, olcum_zinciri.olc).',
     'Maske dogrulandi: %.3f / %.3f cm3 (rapor %.3f / %.3f).' % (h['r'], h['l'], o['hacim_sag'], o['hacim_sol']),
     '', '%-10s %10s %10s' % ('parametre', 'sag', 'sol')]
for k in K:
    L.append('%-10s %10s %10s' % (k, o.get(k + '_sag'), o.get(k + '_sol')))
L += ['', 'IOD_d %s · IOD_mf %s · BOW_ek %s · BOW_fmo %s · centroid %s'
      % (o['IOD_d'], o['IOD_mf'], o['BOW_ek'], o['BOW_fmo'], o['centroid']), '',
      'Denetim: RED %d · UYARI %d' % (sum(u['sonuc'] == 'RED' for u in RAP['denetim']['uyari']),
                                     sum(u['sonuc'] != 'RED' for u in RAP['denetim']['uyari'])),
      '', 'Slicer: sahne dosyasini (.mrml) acin, sonra %s_Segmentation.seg.nrrd -> File > Add Data.' % denek]
open(OUT + '/OKU.txt', 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('TAMAM', OUT)
