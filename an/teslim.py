import sys, os, json, shutil, glob, datetime
sys.path.insert(0, '/home/claude/an'); sys.path.insert(0, '/home/claude/orbita_hat')
import numpy as np, nrrd, onisle, rayseg

OLGU, KAYNAK = sys.argv[1], sys.argv[2]
MRK = '/home/claude/veri_disk/otomatik_landmark/%s_TAMOTO' % OLGU
OUT = '/home/claude/%s_teslim' % OLGU
RAPOR = json.load(open('/home/claude/orbita_hat/raporlar/%s_OTO.json' % OLGU, encoding='utf-8'))
