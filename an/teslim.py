shutil.rmtree(OUT, ignore_errors=True); os.makedirs(OUT)

o, bt, lmr, md = RAPOR['olcum'], RAPOR['bt'], RAPOR['landmark'], RAPOR.get('medial', {})
hacim, bilgi = onisle.dicom_hacim(KAYNAK)
ct = np.transpose(hacim, (2, 1, 0))
org = np.array(bilgi['origin'], float)
rows = np.diag([bilgi['PixelSpacing'][0], bilgi['PixelSpacing'][1], bilgi['kesit_araligi']])
vox = abs(float(np.linalg.det(rows)))
lm = {k: np.array(v, float) for k, v in lmr['nokta'].items()}


def egri(yol):
    d = json.load(open(yol, encoding='utf-8')); P = []
    for m in d['markups']:
        cs = m.get('coordinateSystem', 'LPS')
        for c in m['controlPoints']:
            p = np.array(c['position'], float)
            if cs.upper() == 'LPS':
                p = p * np.array([-1., -1., 1.])
            P.append(p)
    return np.array(P)


E = {'sag': egri(MRK + '/OTO_rim_sag.mrk.json'), 'sol': egri(MRK + '/OTO_rim_sol.mrk.json')}
M = {}
for s, S in (('r', 'sag'), ('l', 'sol')):
    M[s] = rayseg.ray_volume(ct, rows, org, lm, s, rim_curve=E[S], plane_shift=0.0,
                             return_mask=True, acma_mm=1.5)['maske']
h = {s: M[s].sum() * vox / 1000. for s in M}
bek = (o['hacim_sag'], o['hacim_sol'])
dv = (abs(h['r'] - bek[0]), abs(h['l'] - bek[1]))
assert max(dv) < 0.01, 'maske raporla tutmuyor %s' % (dv,)
print('maske dogrulandi: %.3f/%.3f (rapor %.3f/%.3f) · fark %.0f/%.0f voksel'
      % (h['r'], h['l'], bek[0], bek[1], dv[0] * 1000 / vox, dv[1] * 1000 / vox))

nrrd.write(OUT + '/%s_CT.nrrd' % OLGU, ct.astype(np.int16),
           {'type': 'short', 'dimension': 3, 'space': 'left-posterior-superior',
            'sizes': list(ct.shape), 'space directions': rows, 'kinds': ['domain'] * 3,
            'encoding': 'gzip', 'space origin': org}, compression_level=4)
lab = np.zeros(ct.shape, np.uint8); lab[M['r']] = 1; lab[M['l']] = 2
ext = '0 %d 0 %d 0 %d' % (ct.shape[0] - 1, ct.shape[1] - 1, ct.shape[2] - 1)
hdr = {'type': 'unsigned char', 'dimension': 3, 'space': 'left-posterior-superior',
       'sizes': list(ct.shape), 'space directions': rows, 'kinds': ['domain'] * 3,
       'encoding': 'gzip', 'space origin': org,
       'Segmentation_ContainedRepresentationNames': 'Binary labelmap|',
       'Segmentation_ConversionParameters': '',
       'Segmentation_MasterRepresentation': 'Binary labelmap',
       'Segmentation_ReferenceImageExtentOffset': '0 0 0'}
for i, (nm, col) in enumerate((('sag', '0.2 0.9 0.2'), ('sol', '0.9 0.2 0.2'))):
    hdr.update({'Segment%d_ID' % i: nm, 'Segment%d_Name' % i: nm,
                'Segment%d_NameAutoGenerated' % i: '0', 'Segment%d_Color' % i: col,
                'Segment%d_LabelValue' % i: str(i + 1), 'Segment%d_Layer' % i: '0',
                'Segment%d_Extent' % i: ext,
                'Segment%d_Tags' % i: 'Segmentation.Status:inprogress|'})
nrrd.write(OUT + '/%s_Segmentation.seg.nrrd' % OLGU, lab, hdr, compression_level=4)
n = 0
for f in sorted(glob.glob(MRK + '/*.mrk.json')):
    shutil.copy(f, OUT); n += 1

